#!/usr/bin/env node
/**
 * Embed the community guide data into the userscript.
 *
 *   node tools/embed-guides.mjs
 *
 * Reads guides/data/*.json in the fixed order below, validates each envelope
 * and its data shape, then replaces the block between the two markers in
 * pokecatch-team-optimizer.user.js with one `const GUIDES = {...};` literal.
 * The block is generated: edit the JSON files, never the userscript block.
 * Idempotent: running it twice with unchanged JSON leaves the file identical.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'guides', 'data');
const SCRIPT = join(ROOT, 'pokecatch-team-optimizer.user.js');
const START = '/* ---------- 9c-0. COMMUNITY GUIDES DATA (generated by tools/embed-guides.mjs from guides/data/*.json — edit those, not this) ---------- */';
const END = '/* ---------- end of generated guides data ---------- */';

const ORDER = ['underground', 'farming', 'berry', 'overnight', 'gem-tiers', 'ru-tiers', 'type-picks', 'catch-teams', 'elite2-teams'];

const SHAPES = {
  underground: ['themes'],
  farming: ['goals', 'topLoops', 'leagueCandy', 'rules'],
  berry: ['berries', 'sources', 'topLoops', 'rules'],
  overnight: ['moneyTop', 'xpTop', 'xpNeed', 'regions'],
  'gem-tiers': ['bestSinks', 'tiers'],
  'ru-tiers': ['pseudoLegendary', 'topRare', 'topUncommon', 'notes'],
  'type-picks': ['types'],
  'catch-teams': ['fights', 'shield'],
  'elite2-teams': ['fights'],
};

const fail = msg => { console.error('embed-guides: ' + msg); process.exit(1); };

const guides = {};
for (const id of ORDER) {
  let raw;
  try { raw = readFileSync(join(DATA, id + '.json'), 'utf8'); }
  catch { fail(`missing guides/data/${id}.json`); }
  let g;
  try { g = JSON.parse(raw); }
  catch (e) { fail(`guides/data/${id}.json does not parse: ${e.message}`); }
  const bad = [];
  if (g.id !== id) bad.push(`id "${g.id}" does not match the file name`);
  for (const k of ['title', 'subject', 'credit']) if (typeof g[k] !== 'string' || !g[k].trim()) bad.push(`missing ${k}`);
  if (!g.board || !g.board.gameVersion || !g.board.build) bad.push('missing board.gameVersion / board.build');
  if (!g.method || !g.method.summary) bad.push('missing method.summary');
  if (!g.method?.algorithm || !Array.isArray(g.method.algorithm.steps) || !g.method.algorithm.steps.length) bad.push('missing method.algorithm.steps');
  if (!g.data || typeof g.data !== 'object' || !Object.keys(g.data).length) bad.push('empty data');
  if (g.data) for (const key of SHAPES[id]) {
    const v = g.data[key];
    const ok = ['rules', 'notes'].includes(key) ? Array.isArray(v) : Array.isArray(v) || (v && typeof v === 'object');
    if (!ok) bad.push(`data.${key} missing or not an array/object`);
  }
  if (bad.length) fail(`${id}: ` + bad.join('; '));
  guides[id] = g;
}

const block = START + '\n' + '  const GUIDES = ' + JSON.stringify(guides, null, 2)
  .split('\n').map((l, i) => i ? '  ' + l : l).join('\n') + ';\n' + END;
const src = readFileSync(SCRIPT, 'utf8');
const a = src.indexOf(START), b = src.indexOf(END);
let out;
if (a >= 0 && b > a) {
  out = src.slice(0, a) + block + src.slice(b + END.length);
} else {
  const anchor = src.indexOf('  /* ------------------------------------------------------------------ *\n   * 10. Boot + actions');
  if (anchor < 0) fail('no insertion anchor (section 10) and no generated block markers');
  out = src.slice(0, anchor) + '  /* ------------------------------------------------------------------ *\n   * 9c-0. Community guides: data, generated from guides/data/*.json\n   * ------------------------------------------------------------------ */\n' + block + '\n\n' + src.slice(anchor);
}
if (out === src) {
  console.log(`embed-guides: unchanged · ${Object.keys(guides).length} guides · ${Buffer.byteLength(block)} bytes embedded`);
} else {
  writeFileSync(SCRIPT, out);
  console.log(`embed-guides: wrote ${Object.keys(guides).length} guides (${ORDER.join(', ')}) · ${Buffer.byteLength(block)} bytes embedded`);
}
